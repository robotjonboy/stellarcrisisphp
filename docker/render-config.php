function sc_env($name, $default = '')
{
	$v = getenv($name);
	if ($v === false || $v === '')
		return $default;
	return $v;
}

function sc_env_bool($name, $default)
{
	$v = getenv($name);
	if ($v === false || $v === '')
		return $default;
	$v = strtolower($v);
	if (in_array($v, array('1', 'true', 'yes', 'on'), true))
		return true;
	if (in_array($v, array('0', 'false', 'no', 'off'), true))
		return false;
	return $default;
}

function load_secrets($path)
{
	$out = array();
	if (!is_file($path))
		return $out;
	foreach (file($path, FILE_IGNORE_NEW_LINES) as $line) {
		$line = trim($line);
		if ($line === '' || $line[0] === '#')
			continue;
		$eq = strpos($line, '=');
		if ($eq === false)
			continue;
		$key = substr($line, 0, $eq);
		$val = substr($line, $eq + 1);
		$len = strlen($val);
		if ($len >= 2 && (($val[0] === "'" && $val[$len - 1] === "'") || ($val[0] === '"' && $val[$len - 1] === '"')))
			$val = substr($val, 1, -1);
		$out[$key] = $val;
	}
	return $out;
}

